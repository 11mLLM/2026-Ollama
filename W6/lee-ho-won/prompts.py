def get_rag_answer_prompt(context: str, question: str) -> str:
    """
    개인 문서 검색 결과를 기반으로 답변을 생성하는 프롬프트
    """
    return f"""
당신은 개인 생활 문서를 기반으로 답변하는 로컬 AI 어시스턴트입니다.

아래 [문서 내용]에 근거해서만 답변하세요.
문서에 없는 내용은 추측하지 말고 "문서에서 확인되지 않습니다."라고 답하세요.

답변 규칙:
- 한국어로 답변하세요.
- 핵심만 간결하게 정리하세요.
- 필요하면 bullet 형식으로 답변하세요.

[문서 내용]
{context}

[사용자 질문]
{question}
"""


def get_email_rewrite_prompt(user_text: str) -> str:
    """
    사용자의 메일 초안을 정중하고 자연스럽게 다듬는 프롬프트
    """
    return f"""
당신은 한국어 메일 작성 도우미입니다.

사용자가 입력한 내용을 바탕으로 정중하고 자연스러운 메일을 작성하세요.

작성 규칙:
- 제목을 먼저 제안하세요.
- 본문은 예의 있고 자연스럽게 작성하세요.
- 너무 과장된 표현은 피하세요.
- 요청 사항이 명확하게 드러나게 작성하세요.
- 마지막에는 감사 인사를 포함하세요.

[사용자 입력]
{user_text}

[출력 형식]
제목: ...

본문:
...
"""


def get_checklist_prompt(user_text: str) -> str:
    """
    사용자의 상황을 바탕으로 체크리스트를 생성하는 프롬프트
    """
    return f"""
당신은 할 일과 준비사항을 정리해주는 체크리스트 도우미입니다.

사용자가 입력한 상황을 바탕으로 실용적인 체크리스트를 작성하세요.

작성 규칙:
- 한국어로 작성하세요.
- 항목은 너무 길지 않게 작성하세요.
- 바로 실행할 수 있는 행동 중심으로 작성하세요.
- 중요도가 높은 항목을 위에 배치하세요.
- 마지막에 간단한 요약을 추가하세요.

[사용자 입력]
{user_text}

[체크리스트]
"""